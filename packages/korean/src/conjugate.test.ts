const ENDINGS = ["요", "아/어서", "았/었어요", "(스)ㅂ니다", "(으)세요", "(으)ㄹ", "(으)ㄴ", "(으)면", "고", "는/(으)ㄴ"];

describe("inflect", () => {
  for (const [lemma, pos, forms] of GOLDEN) {
    it(lemma, () => {
      expect(ENDINGS.map((e) => f(lemma, e, pos))).toEqual(forms);
    });
  }

  it("keeps the other right spellings", () => {
    expect(inflect(w("보다"), "아/어요").alts).toContain("보아요");
    expect(inflect(w("되다"), "아/어서").alts).toContain("되어서");
    expect(inflect(w("하다"), "아/어서").alts).toContain("하여서");
    expect(inflect(w("먹다"), "(으)세요").alts).toContain("먹으세요");
    expect(inflect(w("오다"), "아/어요").alts).toEqual([]);
  });

  it("writes the plain style and reported speech", () => {
    expect(f("가다", "ㄴ/는다")).toBe("간다");
    expect(f("먹다", "ㄴ/는다")).toBe("먹는다");
    expect(f("살다", "ㄴ/는다")).toBe("산다");
    expect(f("좋다", "다", "adjective")).toBe("좋다");
    expect(f("밝히다", "았/었다")).toBe("밝혔다");
    expect(f("오르다", "ㄴ/는다고")).toBe("오른다고");
    expect(f("비싸다", "다고", "adjective")).toBe("비싸다고");
    expect(f("문제이다", "다고", "copula")).toBe("문제라고");
    expect(f("사실이다", "다고", "copula")).toBe("사실이라고");
  });

  it("puts honorific verbs in for -시-", () => {
    expect(f("자다", "(으)세요")).toBe("주무세요");
    expect(f("먹다", "(으)셨어요")).toBe("드셨어요");
    expect(f("말하다", "(으)세요")).toBe("말씀하세요");
    expect(f("있다", "(으)세요", "adjective")).toBe("있으세요");
  });

  it("drops ㄹ only where it should", () => {
    expect(f("살다", "네요")).toBe("사네요");
    expect(f("만들다", "(으)러")).toBe("만들러");
    expect(f("알다", "(으)니까")).toBe("아니까");
    expect(f("놀다", "기")).toBe("놀기");
  });

  it("follows the card's class over the built-in one", () => {
    // 이르다 "to arrive" goes with 러; 이르다 "early" with 르.
    expect(inflect({ lemma: "이르다", cls: "reo" }, "아/어요").form).toBe("이르러요");
    expect(inflect({ lemma: "이르다" }, "아/어요").form).toBe("일러요");
    // 묻다 "to bury" is regular, "to ask" is not.
    expect(inflect({ lemma: "묻다", cls: "regular" }, "아/어요").form).toBe("묻어요");
    expect(inflect({ lemma: "묻다" }, "아/어요").form).toBe("물어요");
  });
});

